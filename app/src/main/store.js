"use strict";
/**
 * Читання й запис файлів користувача: плейлистів, улюбленого, налаштувань.
 *
 * Раніше кожен модуль робив це сам — `writeFileSync` прямо поверх живого
 * файлу, а на будь-яку помилку читання мовчки починав із порожнього. Два
 * наслідки, обидва погані:
 *
 *   1. Запис поверх живого файлу неатомний. Якщо процес урвався посеред нього
 *      (вимкнули світло, вбили програму, диск затнувся), на диску лишався
 *      обрубок — а старого вже не було.
 *   2. Зіпсований файл нічим не відрізнявся від першого запуску. Програма
 *      відкривалась чистою, і людина вирішувала, що їй наснилось, ніби вона
 *      складала плейлисти.
 *
 * Найгірше саме з плейлистами: плейлист із треків, яких ти не завантажував,
 * не існує більше ніде — ані на диску, ані в YouTube. Тільки в цьому файлі.
 */

const fs = require("fs");
const path = require("path");

/**
 * Файли, які не вдалося прочитати цього запуску.
 * @type {Array<{file: string, backup: string, reason: string}>}
 */
const broken = [];

/** Що зламалось цього запуску — інтерфейс питає це один раз на старті. */
function troubles() {
  return broken.map((b) => ({ ...b, name: path.basename(b.file) }));
}

/**
 * Атомний запис.
 *
 * Спершу в сусідній тимчасовий файл, потім перейменування поверх. У межах
 * одного диска перейменування неподільне: на диску лишається або старий
 * файл цілим, або новий цілим — третього не буває.
 *
 * @returns {boolean} чи вдалося зберегти
 */
function writeJson(file, data) {
  const tmp = `${file}.tmp`;
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(tmp, JSON.stringify(data, null, 2), "utf8");
    fs.renameSync(tmp, file);
    return true;
  } catch {
    // Не змогли — прибираємо за собою недописаний хвіст, щоб він не заважав
    // наступного разу. Самі налаштування просто не переживуть перезапуск.
    try {
      fs.rmSync(tmp, { force: true });
    } catch {
      /* і це не вийшло — не варте окремої скарги */
    }
    return false;
  }
}

/**
 * Читання з розрізненням «файлу ще немає» і «файл зіпсований».
 *
 * Перший випадок — звичайний перший запуск, про нього говорити нема чого.
 * Другий означає втрату даних, і мовчати про неї не можна: нечитний файл
 * відкладаємо поруч під `.broken`, щоб його можна було відкрити блокнотом і
 * витягти руками — там звичайний JSON.
 *
 * @param {string} file
 * @param {{fallback: any, valid?: (v: any) => boolean}} opts
 */
function readJson(file, { fallback, valid }) {
  let raw;
  try {
    raw = fs.readFileSync(file, "utf8");
  } catch (e) {
    // ENOENT — файлу просто немає, це нормальний перший запуск.
    if (e.code !== "ENOENT") keepBroken(file, e.message);
    return fallback;
  }

  let data;
  try {
    data = JSON.parse(raw);
  } catch (e) {
    keepBroken(file, e.message);
    return fallback;
  }

  // Правильний JSON із неправильним вмістом — теж псування: колись давно
  // так з'являлись плейлисти-не-масиви після невдалого оновлення формату.
  if (valid && !valid(data)) {
    keepBroken(file, "вміст не той, на який ми розраховували");
    return fallback;
  }

  return data;
}

/** Відкладає нечитний файл убік, щоб наступний запис його не затер. */
function keepBroken(file, reason) {
  const backup = `${file}.broken`;
  try {
    // Попередній зламаний прибираємо: тримати їхню колекцію ні до чого,
    // а свіжий важливіший за торішній.
    fs.rmSync(backup, { force: true });
    fs.renameSync(file, backup);
  } catch {
    /* навіть відкласти не вийшло — принаймні скажемо, що файл не прочитався */
  }
  broken.push({ file, backup, reason });
}

module.exports = { readJson, writeJson, troubles };
